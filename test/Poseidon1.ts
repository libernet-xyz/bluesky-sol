/** The limit on the size of deployed code (EIP-170). */
const MAX_CODE_SIZE = 24576;

/** The permutation libraries, identified by their state width and their S-box exponent. */
const PERMUTATIONS: { width: number; alpha: number }[] = [
  { width: 3, alpha: 5 },
  { width: 4, alpha: 5 },
  { width: 5, alpha: 5 },
  { width: 3, alpha: 7 },
  { width: 4, alpha: 7 },
  { width: 5, alpha: 7 },
];

/** A permutation test case generated by `tools/poseidon1` with the `starkom-poseidon` crate. */
interface PermutationCase {
  width: number;
  alpha: number;
  input: string[];
  output: string[];
}

/** A sponge test case generated by `tools/poseidon1` with the `starkom-poseidon` crate. */
interface HashCase {
  width: number;
  alpha: number;
  dst: string[];
  inputs: string[];
  output: string[];
}

const vectors: { permutations: PermutationCase[]; hashes: HashCase[] } = JSON.parse(
  readFileSync(new URL("./vectors/poseidon1.json", import.meta.url), "utf8"),
);

/** The suffix that identifies a permutation in Solidity names, e.g. `T3X5`. */
function suffix(width: number, alpha: number): string {
  return `T${width}X${alpha}`;
}

