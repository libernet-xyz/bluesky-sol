import { expect } from "chai";
import { network } from "hardhat";
import type { BaseContract } from "ethers";
import { readFileSync } from "node:fs";
import type { Poseidon2Harness } from "../types/ethers-contracts/index.js";

const { ethers } = await network.create();

const P = 0x7ffffffffffffffffffffffffffffffe0673ddf29e9b5547c000000000000001n;

/** The limit on the size of deployed code (EIP-170). */
const MAX_CODE_SIZE = 24576;

/** The permutation libraries, identified by their state width and their S-box exponent. */
const PERMUTATIONS: { width: number; alpha: number }[] = [
  { width: 3, alpha: 5 },
  { width: 4, alpha: 5 },
];

/** A permutation test case generated by `tools/poseidon2` with the `starkom-poseidon2` crate. */
interface PermutationCase {
  width: number;
  alpha: number;
  input: string[];
  output: string[];
}

/** A sponge test case generated by `tools/poseidon2` with the `starkom-poseidon2` crate. */
interface HashCase {
  width: number;
  alpha: number;
  dst: string[];
  inputs: string[];
  output: string[];
}

const vectors: { permutations: PermutationCase[]; hashes: HashCase[] } = JSON.parse(
  readFileSync(new URL("./vectors/poseidon2.json", import.meta.url), "utf8"),
);

/** The suffix that identifies a permutation in Solidity names, e.g. `T3X5`. */
function suffix(width: number, alpha: number): string {
  return `T${width}X${alpha}`;
}

// From the `test_permutation_t*` tests of the `starkom-poseidon2` crate: the permutations of
// [0, 1, ..., T - 1].
const RUST_PERMUTATIONS: Record<string, bigint[]> = {
  T3X5: [
    0x6f30582cde48a25b26015b7f718ba2fb359e93029caf04d8d0b3e66b1d46b941n,
    0x5de8159372063ce76403529bb1a9725461b96467035d906400ff48d0937f9db6n,
    0x3c88b37dc6d14d08960b6fe58344e09194d11a930ce9f60cc90294683fac4b9fn,
  ],
  T4X5: [
    0x775049834d9decb40ec5a109116a27527fa9105a3521cee8a42777788fda1501n,
    0x630ded08b39ceac4859c9ab6d14b548f48d01164ce1efada3a7a868f7d9248cbn,
    0x14b47f414dececb9936dcbb89e2fdd8511c44acb30439d1d23e48119b1c03b4fn,
    0x72de70292ce1ac7f30b859d04bbb6de5377288c1192a08863c34e11bc9269c4cn,
  ],
};

/** Returns [0, 1, ..., width - 1]. */
function counting(width: number): bigint[] {
  return Array.from({ length: width }, (_, i) => BigInt(i));
}

describe("Poseidon2", function () {
  let harness: Poseidon2Harness;

  /** The deployed libraries by name. They also define the errors of the sponge functions. */
  const libraries: Record<string, BaseContract> = {};

  before(async function () {
    const addresses: Record<string, string> = {};
    for (const { width, alpha } of PERMUTATIONS) {
      const name = `Poseidon2${suffix(width, alpha)}`;
      libraries[name] = await ethers.deployContract(name);
      addresses[name] = await libraries[name].getAddress();
    }
    harness = await ethers.deployContract("Poseidon2Harness", [], { libraries: addresses });
  });

  function permute(width: number, alpha: number, state: bigint[]): Promise<bigint[]> {
    return harness.getFunction(`permute${suffix(width, alpha)}`)(state);
  }

  function hash(width: number, alpha: number, dst: bigint[], inputs: bigint[]): Promise<bigint[]> {
    return harness.getFunction(`hash${suffix(width, alpha)}`)(dst, inputs);
  }

  function hash0(width: number, alpha: number, dst: bigint[], inputs: bigint[]): Promise<bigint> {
    return harness.getFunction(`hash0${suffix(width, alpha)}`)(dst, inputs);
  }

  describe("permutation libraries", function () {
    for (const { width, alpha } of PERMUTATIONS) {
      const name = `Poseidon2${suffix(width, alpha)}`;
      const expected = RUST_PERMUTATIONS[suffix(width, alpha)];

      it(`${name} fits in the contract size limit`, async function () {
        const code = await ethers.provider.getCode(libraries[name]);
        expect(ethers.dataLength(code)).to.be.lessThanOrEqual(MAX_CODE_SIZE);
      });

      it(`${name} matches the Rust unit test`, async function () {
        expect(await permute(width, alpha, counting(width))).to.deep.equal(expected);
      });

      it(`${name} reduces non-canonical inputs`, async function () {
        const state = counting(width).map((value) => value + P);
        expect(await permute(width, alpha, state)).to.deep.equal(expected);
      });
    }

    for (const { width, alpha, input, output } of vectors.permutations) {
      const name = `Poseidon2${suffix(width, alpha)}`;
      it(`${name} permutes [${input[0].slice(0, 10)}..., ...]`, async function () {
        expect(await permute(width, alpha, input.map(BigInt))).to.deep.equal(output.map(BigInt));
      });
    }
  });

  describe("sponge", function () {
    for (const { width, alpha, dst, inputs, output } of vectors.hashes) {
      const name = suffix(width, alpha);
      const description =
        `hash${name} with capacity ${dst.length} and ${inputs.length} inputs ` +
        `[${inputs[0].slice(0, 10)}..., ...]`;

      it(description, async function () {
        expect(await hash(width, alpha, dst.map(BigInt), inputs.map(BigInt))).to.deep.equal(
          output.map(BigInt),
        );
      });

      it(`hash0${name} with the same arguments`, async function () {
        expect(await hash0(width, alpha, dst.map(BigInt), inputs.map(BigInt))).to.equal(
          BigInt(output[0]),
        );
      });
    }

    // Same as the `test_capacity_dst_t*` tests of the `starkom-poseidon2` crate: with the tag
    // T - 1 and the inputs [0, 1, ..., T - 2] the state is [0, 1, ..., T - 1] when it's permuted.
    for (const { width, alpha } of PERMUTATIONS) {
      const name = suffix(width, alpha);
      it(`hash${name} initializes the capacity with the tags`, async function () {
        const inputs = counting(width - 1);
        expect(await hash(width, alpha, [BigInt(width - 1)], inputs)).to.deep.equal(
          RUST_PERMUTATIONS[name].slice(0, width - 1),
        );
      });
    }

    for (const { width, alpha } of PERMUTATIONS) {
      const name = suffix(width, alpha);
      const libraryName = `Poseidon2${name}`;

      it(`hash${name} rejects empty inputs`, async function () {
        await expect(hash(width, alpha, [0n], [])).to.be.revertedWithCustomError(
          libraries[libraryName],
          "EmptyInput",
        );
      });

      it(`hash${name} rejects a capacity equal to the width`, async function () {
        await expect(hash(width, alpha, new Array(width).fill(0n), [1n]))
          .to.be.revertedWithCustomError(libraries[libraryName], "InvalidCapacity")
          .withArgs(width, width);
      });

      it(`hash${name} rejects a capacity larger than the width`, async function () {
        await expect(hash(width, alpha, new Array(width + 1).fill(0n), [1n]))
          .to.be.revertedWithCustomError(libraries[libraryName], "InvalidCapacity")
          .withArgs(width + 1, width);
      });

      it(`hash${name} rejects a non-canonical input`, async function () {
        await expect(hash(width, alpha, [0n], [1n, P]))
          .to.be.revertedWithCustomError(libraries[libraryName], "NonCanonicalInput")
          .withArgs(P);
      });

      it(`hash${name} rejects a non-canonical tag`, async function () {
        await expect(hash(width, alpha, [P + 1n], [1n]))
          .to.be.revertedWithCustomError(libraries[libraryName], "NonCanonicalInput")
          .withArgs(P + 1n);
      });
    }
  });
});
