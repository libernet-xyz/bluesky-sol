/** Returns [0, 1, ..., width - 1]. */
function counting(width: number): bigint[] {
  return Array.from({ length: width }, (_, i) => BigInt(i));
}

describe("Poseidon1", function () {
  let harness: Poseidon1Harness;
  const libraries: Record<string, string> = {};

  before(async function () {
    for (const { width, alpha } of PERMUTATIONS) {
      const name = `Poseidon1${suffix(width, alpha)}`;
      const library = await ethers.deployContract(name);
      libraries[name] = await library.getAddress();
    }
    harness = await ethers.deployContract("Poseidon1Harness", [], { libraries });
  });

  function permute(width: number, alpha: number, state: bigint[]): Promise<bigint[]> {
    return harness.getFunction(`permute${suffix(width, alpha)}`)(state);
  }

  function hash(width: number, alpha: number, dst: bigint[], inputs: bigint[]): Promise<bigint[]> {
    return harness.getFunction(`hash${suffix(width, alpha)}`)(dst, inputs);
  }

  function hash0(width: number, alpha: number, dst: bigint[], inputs: bigint[]): Promise<bigint> {
    return harness.getFunction(`hash0${suffix(width, alpha)}`)(dst, inputs);
  }

  describe("permutation libraries", function () {
    for (const { width, alpha } of PERMUTATIONS) {
      const name = `Poseidon1${suffix(width, alpha)}`;
      const expected = RUST_PERMUTATIONS[suffix(width, alpha)];

      it(`${name} fits in the contract size limit`, async function () {
        const code = await ethers.provider.getCode(libraries[name]);
        expect(ethers.dataLength(code)).to.be.lessThanOrEqual(MAX_CODE_SIZE);
      });

      it(`${name} matches the Rust unit test`, async function () {
        expect(await permute(width, alpha, counting(width))).to.deep.equal(expected);
      });

      it(`${name} reduces non-canonical inputs`, async function () {
        const state = counting(width).map((value) => value + P);
        expect(await permute(width, alpha, state)).to.deep.equal(expected);
      });
    }

    for (const { width, alpha, input, output } of vectors.permutations) {
      const name = `Poseidon1${suffix(width, alpha)}`;
      it(`${name} permutes [${input[0].slice(0, 10)}..., ...]`, async function () {
        expect(await permute(width, alpha, input.map(BigInt))).to.deep.equal(output.map(BigInt));
      });
    }
  });

  describe("sponge", function () {
    for (const { width, alpha, dst, inputs, output } of vectors.hashes) {
      const name = suffix(width, alpha);
      const description =
        `hash${name} with capacity ${dst.length} and ${inputs.length} inputs ` +
        `[${inputs[0].slice(0, 10)}..., ...]`;

      it(description, async function () {
        expect(await hash(width, alpha, dst.map(BigInt), inputs.map(BigInt))).to.deep.equal(
          output.map(BigInt),
        );
      });

      it(`hash0${name} with the same arguments`, async function () {
        expect(await hash0(width, alpha, dst.map(BigInt), inputs.map(BigInt))).to.equal(
          BigInt(output[0]),
        );
      });
    }

    // Same as the `test_capacity_dst_t*` tests of the `starkom-poseidon` crate: with the tag
    // T - 1 and the inputs [0, 1, ..., T - 2] the state is [0, 1, ..., T - 1] when it's permuted.
    for (const { width, alpha } of PERMUTATIONS) {
      const name = suffix(width, alpha);
      it(`hash${name} initializes the capacity with the tags`, async function () {
        const inputs = counting(width - 1);
        expect(await hash(width, alpha, [BigInt(width - 1)], inputs)).to.deep.equal(
          RUST_PERMUTATIONS[name].slice(0, width - 1),
        );
      });
    }

    for (const { width, alpha } of PERMUTATIONS) {
      const name = suffix(width, alpha);

      it(`hash${name} rejects empty inputs`, async function () {
        await expect(hash(width, alpha, [0n], [])).to.be.revertedWithCustomError(
          harness,
          "EmptyInput",
        );
      });

      it(`hash${name} rejects a capacity equal to the width`, async function () {
        await expect(hash(width, alpha, new Array(width).fill(0n), [1n]))
          .to.be.revertedWithCustomError(harness, "InvalidCapacity")
          .withArgs(width, width);
      });

      it(`hash${name} rejects a capacity larger than the width`, async function () {
        await expect(hash(width, alpha, new Array(width + 1).fill(0n), [1n]))
          .to.be.revertedWithCustomError(harness, "InvalidCapacity")
          .withArgs(width + 1, width);
      });

      it(`hash${name} rejects a non-canonical input`, async function () {
        await expect(hash(width, alpha, [0n], [1n, P]))
          .to.be.revertedWithCustomError(harness, "NonCanonicalInput")
          .withArgs(P);
      });

      it(`hash${name} rejects a non-canonical tag`, async function () {
        await expect(hash(width, alpha, [P + 1n], [1n]))
          .to.be.revertedWithCustomError(harness, "NonCanonicalInput")
          .withArgs(P + 1n);
      });
    }
  });
});
